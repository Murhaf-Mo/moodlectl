# Phase 2 — diff: parsed YAML  →  list[Change]
# ---------------------------------------------------------------------------

# Change kinds
CREATE_CATEGORY = "CREATE_CATEGORY"
UPDATE_CATEGORY = "UPDATE_CATEGORY"
CREATE_ITEM = "CREATE_ITEM"
UPDATE_ITEM = "UPDATE_ITEM"
MOVE_ITEM = "MOVE_ITEM"
SET_CALCULATION = "SET_CALCULATION"
DELETE_ITEM = "DELETE_ITEM"
SET_MODULE_VISIBLE = "SET_MODULE_VISIBLE"


@dataclass
class Change:
    """A single declarative operation to apply against the gradebook.

    `target_eid` identifies the live node when known (eid like "cg12" or
    "ig345"). For CREATE_*, target_eid is "" and `parent_cat_id` carries the
    intended parent. `payload` holds the Moodle form-field changes verbatim
    (already translated from friendly YAML names to Moodle's form keys).
    """
    kind: str
    label: str  # human-readable, shown in the diff summary
    payload: dict[str, str] = field(default_factory=dict)
    target_eid: str = ""
    target_item_id: int = 0      # for SET_CALCULATION + UPDATE_ITEM
    target_cat_id: int = 0       # for UPDATE_CATEGORY
    parent_cat_id: int = 0       # for CREATE_*
    # SET_CALCULATION extras
    formula: str = ""
    idnumber_overrides: dict[int, str] = field(default_factory=dict)
    # CREATE_ITEM extras — the YAML node so push() can wire up calculation/idnumber afterwards
    yaml_node: dict[str, Any] = field(default_factory=dict)
    # MOVE_ITEM extras
    target_parent_cat_id: int = 0   # destination category
    # Two-pass push support: when the parent category was CREATED in the same
    # push, target_parent_cat_id starts at 0 and `pending_parent_tag` carries
    # a stable label that resolves to the real cat_id at apply time.
    pending_parent_tag: str = ""
    # CREATE_CATEGORY emits its own tag so dependent operations can resolve it.
    own_tag: str = ""
    # When set, push routes the idnumber update through the calc-form trick
    # (item.php silently ignores idnumber on activity-backed grade items).
    via_calc_form: bool = False
    course_total_item_id: int = 0   # filled at push time


# ── Helpers ───────────────────────────────────────────────────────────────

def _flatten_live(cat: GradeCategory) -> tuple[dict[str, GradeCategory], dict[str, GradeItem]]:
    """Return ({eid: category}, {eid: item}) for every node under cat (inclusive)."""
    cats: dict[str, GradeCategory] = {cat["eid"]: cat}
    items: dict[str, GradeItem] = {}
    for sub in cat["subcategories"]:
        sub_cats, sub_items = _flatten_live(sub)
        cats.update(sub_cats)
        items.update(sub_items)
    for it in cat["items"]:
        items[it["eid"]] = it
    return cats, items


def _live_item_by_cmid(items: dict[str, GradeItem]) -> dict[int, GradeItem]:
    return {int(it["cmid"]): it for it in items.values() if it.get("cmid")}


def _live_item_by_idnumber(items: dict[str, GradeItem]) -> dict[str, GradeItem]:
    return {it["idnumber"]: it for it in items.values() if it.get("idnumber")}


def _match_item(node: dict[str, Any], live_items: dict[str, GradeItem]) -> GradeItem | None:
    """Find a live item matching the YAML node by (in priority order) eid, cmid, idnumber."""
    eid = node.get("eid")
    if eid and eid in live_items:
        return live_items[eid]
    cmid = node.get("cmid")
    if cmid:
        by_cmid = _live_item_by_cmid(live_items)
        if int(cmid) in by_cmid:
            return by_cmid[int(cmid)]
    idnum = node.get("idnumber")
    if idnum:
        by_idn = _live_item_by_idnumber(live_items)
        if idnum in by_idn:
            return by_idn[idnum]
    return None


def _walk_yaml(
        node: dict[str, Any],
        parent_cat_id: int,
        live_cats: dict[str, GradeCategory],
        live_items: dict[str, GradeItem],
        changes: list[Change],
        parent_tag: str = "",
) -> None:
    """Recursively diff a YAML category node into Change objects.

    `parent_tag` is non-empty when the parent category is being CREATED in
    this same push (not yet in the live tree). Children inherit the tag so
    push() can resolve their real parent cat_id after the CREATE succeeds.
    """
    eid = node.get("eid", "")
    yaml_name = node.get("name", "")

    live: GradeCategory | None = live_cats.get(eid) if eid else None

    if live is None:
        # CREATE_CATEGORY — emit a stable tag children can refer back to.
        own_tag = f"__pending_cat_{id(node):x}__"
        payload = _category_yaml_to_form_changes(node, include_required=True)
        changes.append(Change(
            kind=CREATE_CATEGORY,
            label=f"create category {yaml_name!r} under cat#{parent_cat_id}",
            payload=payload,
            parent_cat_id=parent_cat_id,
            pending_parent_tag=parent_tag,  # parent might also be brand-new
            own_tag=own_tag,
            yaml_node=node,
        ))
        new_parent = 0
        new_parent_tag = own_tag
    else:
        # UPDATE_CATEGORY if attributes differ
        payload = _category_diff_payload(node, live)
        if payload:
            changes.append(Change(
                kind=UPDATE_CATEGORY,
                label=f"update category {live['name']!r} ({eid}): {sorted(payload)}",
                payload=payload,
                target_eid=eid,
                target_cat_id=int(live["cat_id"]),
            ))
        # Calculation override on the category's grade_item
        yaml_calc = (node.get("calculation") or "").strip()
        live_calc = (live.get("calculation") or "").strip()
        if yaml_calc != live_calc:
            changes.append(Change(
                kind=SET_CALCULATION,
                label=f"set calculation on category {live['name']!r} ({eid})",
                target_eid=eid,
                target_item_id=int(live["item_id"]),
                formula=yaml_calc,
            ))
        new_parent = int(live["cat_id"])
        new_parent_tag = ""

    # Recurse children
    for child_wrapper in node.get("children", []) or []:
        if "category" in child_wrapper:
            _walk_yaml(child_wrapper["category"], new_parent, live_cats, live_items, changes, parent_tag=new_parent_tag)
        elif "item" in child_wrapper:
            _diff_item(child_wrapper["item"], new_parent, live_items, changes, parent_tag=new_parent_tag)


def _diff_item(
        node: dict[str, Any],
        parent_cat_id: int,
        live_items: dict[str, GradeItem],
        changes: list[Change],
        parent_tag: str = "",
) -> None:
    live = _match_item(node, live_items)
    if live is None:
        kind = node.get("kind", "manual")
        if kind not in ("manual", "calculated"):
            # We can't create activity-backed items via the gradebook UI — they
            # come from creating the underlying module (assign/quiz). Skip with
            # a warning embedded in label so the user notices in the diff.
            changes.append(Change(
                kind=CREATE_ITEM,
                label=f"SKIP create {kind!r} item {node.get('name')!r} (must be created via the module)",
                payload={},
                parent_cat_id=parent_cat_id,
                pending_parent_tag=parent_tag,
                yaml_node=node,
            ))
            return
        payload = _item_yaml_to_form_changes(node, include_required=True)
        changes.append(Change(
            kind=CREATE_ITEM,
            label=f"create {kind} item {node.get('name')!r} under cat#{parent_cat_id} (max={node.get('grademax')})",
            payload=payload,
            parent_cat_id=parent_cat_id,
            pending_parent_tag=parent_tag,
            yaml_node=node,
        ))
        return

    # Detect MOVE: the YAML wraps this item under a parent category whose
    # cat_id differs from the live parent. parent_cat_id is the cat_id of
    # the enclosing YAML category node.
    live_parent = int(live.get("parent_cat_id") or 0)
    # A move is needed when either:
    #  - parent_cat_id is concrete and differs from live, OR
    #  - parent_cat_id == 0 (sentinel) but we have a pending_parent_tag —
    #    meaning the parent is being created in this same push.
    needs_move = (parent_cat_id and parent_cat_id != live_parent) or (
            not parent_cat_id and parent_tag and live_parent
    )
    if needs_move:
        changes.append(Change(
            kind=MOVE_ITEM,
            label=(f"move item {live['name']!r} ({live['eid']}) "
                   f"→ {'new cat (' + parent_tag + ')' if parent_tag else f'cat#{parent_cat_id}'}"),
            target_eid=live["eid"],
            target_item_id=int(live["item_id"]),
            target_parent_cat_id=parent_cat_id,
            pending_parent_tag=parent_tag,
        ))

    # SET_MODULE_VISIBLE: activity items can change `module_visible` (default True).
    if live.get("cmid"):
        yaml_vis = node.get("module_visible")
        live_vis = live.get("module_visible", True)
        if yaml_vis is not None and bool(yaml_vis) != bool(live_vis):
            changes.append(Change(
                kind=SET_MODULE_VISIBLE,
                label=(f"set module {'visible' if yaml_vis else 'hidden'} on "
                       f"{live['name']!r} (cmid={live['cmid']})"),
                target_eid=live["eid"],
                target_item_id=int(live["item_id"]),
                payload={"cmid": str(int(live["cmid"])), "visible": "1" if yaml_vis else "0"},
            ))

    payload = _item_diff_payload(node, live)
    # For activity-backed items, idnumber changes must be routed through the
    # calc-form override mechanism (item.php silently ignores them). Split
    # off idnumber into a separate Change so push handles it correctly.
    is_activity_backed = bool(live.get("cmid"))
    if payload and "idnumber" in payload and is_activity_backed:
        new_idnumber = payload.pop("idnumber")
        changes.append(Change(
            kind=UPDATE_ITEM,
            label=f"set idnumber on activity item {live['name']!r} ({live['eid']}) → {new_idnumber!r}",
            payload={"idnumber": new_idnumber},
            target_eid=live["eid"],
            target_item_id=int(live["item_id"]),
            via_calc_form=True,
        ))

    if payload:
        changes.append(Change(
            kind=UPDATE_ITEM,
            label=f"update item {live['name']!r} ({live['eid']}): {sorted(payload)}",
            payload=payload,
            target_eid=live["eid"],
            target_item_id=int(live["item_id"]),
        ))
    yaml_calc = (node.get("calculation") or "").strip()
    live_calc = (live.get("calculation") or "").strip()
    if yaml_calc != live_calc:
        changes.append(Change(
            kind=SET_CALCULATION,
            label=f"set calculation on item {live['name']!r} ({live['eid']})",
            target_eid=live["eid"],
            target_item_id=int(live["item_id"]),
            formula=yaml_calc,
        ))


# ── YAML-friendly  ↔  Moodle form key translation ────────────────────────

def _category_yaml_to_form_changes(node: dict[str, Any], *, include_required: bool) -> dict[str, str]:
    """Translate a YAML category dict to Moodle category.php form-field changes.

    `include_required=True` is used for CREATE (must include `fullname` and
    `aggregation`); UPDATE callers omit fields they don't want to change.
    """
    out: dict[str, str] = {}
    if "name" in node or include_required:
        out["fullname"] = str(node.get("name", ""))
    if "aggregation" in node or include_required:
        agg_name = node.get("aggregation", "sum")
        out["aggregation"] = str(AGGREGATION_BY_NAME[agg_name])
    if "droplow" in node:
        out["droplow"] = str(int(node["droplow"]))
    if "keephigh" in node:
        out["keephigh"] = str(int(node["keephigh"]))
    if "aggregateonlygraded" in node:
        out["aggregateonlygraded"] = "1" if node["aggregateonlygraded"] else "0"
    if "aggregateoutcomes" in node:
        out["aggregateoutcomes"] = "1" if node["aggregateoutcomes"] else "0"
    if "grademax" in node:
        out["grade_item_grademax"] = f"{float(node['grademax']):.2f}"
    if "idnumber" in node:
        out["grade_item_idnumber"] = str(node["idnumber"])
    if "hidden" in node:
        out["grade_item_hidden"] = "1" if node["hidden"] else "0"
    if "weight_override" in node:
        out["grade_item_weightoverride"] = "1" if node["weight_override"] else "0"
    if "weight" in node and node["weight"] is not None:
        out["grade_item_aggregationcoef"] = f"{float(node['weight']):.4f}"
    if "aggregationcoef2" in node and node["aggregationcoef2"] is not None:
        out["grade_item_aggregationcoef2"] = f"{float(node['aggregationcoef2']):.4f}"
    return out


def _category_diff_payload(node: dict[str, Any], live: GradeCategory) -> dict[str, str]:
    """Return only the form-field changes for an UPDATE (differs from live)."""
    out: dict[str, str] = {}
    if "name" in node and node["name"] != live["name"]:
        out["fullname"] = str(node["name"])
    if "aggregation" in node and node["aggregation"] != live["aggregation"]:
        out["aggregation"] = str(AGGREGATION_BY_NAME[node["aggregation"]])
    if "droplow" in node and int(node["droplow"]) != int(live.get("droplow") or 0):
        out["droplow"] = str(int(node["droplow"]))
    if "keephigh" in node and int(node["keephigh"]) != int(live.get("keephigh") or 0):
        out["keephigh"] = str(int(node["keephigh"]))
    if "grademax" in node and abs(float(node["grademax"]) - float(live.get("grademax", 0.0))) > 1e-6:
        out["grade_item_grademax"] = f"{float(node['grademax']):.2f}"
    if "idnumber" in node and str(node["idnumber"]) != str(live.get("idnumber") or ""):
        out["grade_item_idnumber"] = str(node["idnumber"])
    if "hidden" in node and bool(node["hidden"]) != bool(live.get("hidden")):
        out["grade_item_hidden"] = "1" if node["hidden"] else "0"
    if "weight_override" in node and bool(node["weight_override"]) != bool(live.get("weight_override")):
        out["grade_item_weightoverride"] = "1" if node["weight_override"] else "0"
    if "weight" in node and node["weight"] is not None:
        live_w = live.get("weight")
        if live_w is None or abs(float(node["weight"]) - float(live_w)) > 1e-6:
            out["grade_item_aggregationcoef"] = f"{float(node['weight']):.4f}"
    if "aggregationcoef2" in node and node["aggregationcoef2"] is not None:
        live_c = live.get("aggregationcoef2")
        if live_c is None or abs(float(node["aggregationcoef2"]) - float(live_c)) > 1e-6:
            out["grade_item_aggregationcoef2"] = f"{float(node['aggregationcoef2']):.4f}"
    return out


def _item_yaml_to_form_changes(node: dict[str, Any], *, include_required: bool) -> dict[str, str]:
    """Translate a YAML item dict to Moodle item.php form-field changes.

    Note: item.php uses bare keys (`itemname`, `idnumber`, `grademax`), not
    `grade_item_*` prefixed (those are category.php-only).
    """
    out: dict[str, str] = {}
    if "name" in node or include_required:
        out["itemname"] = str(node.get("name", ""))
    if "grademax" in node or include_required:
        out["grademax"] = f"{float(node.get('grademax', 0.0)):.2f}"
    if "idnumber" in node:
        out["idnumber"] = str(node["idnumber"])
    if "hidden" in node:
        out["hidden"] = "1" if node["hidden"] else "0"
    if "locked" in node:
        out["locked"] = "1" if node["locked"] else "0"
    if "weight_override" in node:
        out["weightoverride"] = "1" if node["weight_override"] else "0"
    if "weight" in node and node["weight"] is not None:
        out["aggregationcoef"] = f"{float(node['weight']):.4f}"
    if "aggregationcoef2" in node and node["aggregationcoef2"] is not None:
        out["aggregationcoef2"] = f"{float(node['aggregationcoef2']):.4f}"
    # `itemtype` is required for create; manual is the only user-creatable kind.
    if include_required:
        out["itemtype"] = "manual"
    return out


