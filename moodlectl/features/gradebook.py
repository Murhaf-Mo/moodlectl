"""YAML pull/diff/push for the Moodle gradebook setup.

Phase 1 (read-only): `pull()` only — serialise a course's full gradebook
(categories + grade items + calculations) to a YAML string suitable for
inspection or later round-trip via Phase 2/3 `diff()` / `push()`.

The serialised shape mirrors the live tree exactly: categories nest their
subcategories and items in the same order Moodle renders them. Identity is
carried by `eid` (e.g. `cg1524`, `ig7166`); pure-string keys allow YAML
editors to safely round-trip the file without quoting concerns.

`features/content_yaml.py` is the sibling pattern this module imitates.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable

import yaml

from moodlectl.types import (
    AGGREGATION_BY_NAME,
    CourseId,
    GradeCategory,
    GradeCategoryId,
    GradeItem,
    GradeItemId,
    GradeTree,
    MoodleClientProtocol,
)

# Progress callback: (current, total, description) -> None
ProgressCb = Callable[[int, int, str], None]


_HEADER = """\
# Generated by moodlectl gradebook pull.
#
# Editable on a future `gradebook push`:
#   - category: name, aggregation, droplow, keephigh, grademax, weight,
#     weight_override, hidden, idnumber, aggregateonlygraded
#   - item:     name (manual only), grademax (manual only), weight,
#     weight_override, hidden, idnumber, calculation (any item)
#   - structure: nest order; manual items may be added/removed
#
# Read-only (round-tripped verbatim):
#   - course_id, eid (cgN / igN), item_id, cmid, kind ("quiz" / "assign" /
#     "manual" / "calculated" / "mod")
#
# Aggregation names: sum, mean, mean_of_grades, median, min, max, mode,
#   weighted_mean, simple_weighted_mean
#
# Tip: commit this file to git before any future push — that is your undo.
"""


# ---------------------------------------------------------------------------
# Serialisation helpers
# ---------------------------------------------------------------------------

def _round(x: float | None) -> float | None:
    if x is None:
        return None
    # Strip Moodle's trailing zeros (20.00000) without losing precision.
    return round(float(x), 5)


def _enrich_category(
        client: MoodleClientProtocol,
        course_id: CourseId,
        cat: GradeCategory,
        progress: ProgressCb | None,
        counter: list[int],
        total: int,
) -> None:
    """Fetch per-category settings (droplow, idnumber, …) from category.php."""
    counter[0] += 1
    if progress:
        progress(counter[0], total, f"category: {cat['name']}")
    form = client.get_grade_category_form(course_id, cat["cat_id"])  # type: ignore[arg-type]
    cat["droplow"] = int(form.get("droplow") or 0)
    cat["keephigh"] = int(form.get("keephigh") or 0)
    cat["aggregateonlygraded"] = bool(int(form.get("aggregateonlygraded") or 0))
    cat["aggregateoutcomes"] = bool(int(form.get("aggregateoutcomes") or 0))
    cat["idnumber"] = form.get("grade_item_idnumber") or ""
    coef2 = form.get("grade_item_aggregationcoef2") or ""
    cat["aggregationcoef2"] = float(coef2) if coef2 else None
    coef = form.get("grade_item_aggregationcoef") or ""
    cat["weight"] = float(coef) if coef and coef != "0" else None
    cat["weight_override"] = bool(int(form.get("grade_item_weightoverride") or 0))
    # A category's grade_item may carry a calculation override; capture it.
    try:
        formula, _ = client.get_grade_calculation(course_id, cat["item_id"])  # type: ignore[arg-type]
    except Exception:
        formula = ""
    if formula:
        cat["calculation"] = formula


def _enrich_item(
        client: MoodleClientProtocol,
        course_id: CourseId,
        item: GradeItem,
        progress: ProgressCb | None,
        counter: list[int],
        total: int,
) -> None:
    """Fetch per-item settings (idnumber, calculation, …) from item.php + calculation.php."""
    counter[0] += 1
    if progress:
        progress(counter[0], total, f"item: {item['name']}")
    form = client.get_grade_item_form(course_id, item["item_id"])  # type: ignore[arg-type]
    item["idnumber"] = form.get("idnumber") or ""
    coef2 = form.get("aggregationcoef2") or ""
    item["aggregationcoef2"] = float(coef2) if coef2 else None
    coef = form.get("aggregationcoef") or ""
    item["weight"] = float(coef) if coef and coef != "0" else None
    item["weight_override"] = bool(int(form.get("weightoverride") or 0))
    item["locked"] = bool(int(form.get("locked") or 0))

    # Only manual items can hold a calculation. Activity-backed items can too,
    # but it's rare; fetch defensively. Skip categoryitem/courseitem (handled
    # at category level).
    try:
        formula, _ref_idmap = client.get_grade_calculation(course_id, item["item_id"])  # type: ignore[arg-type]
    except Exception:
        formula = ""
    item["calculation"] = formula or ""
    if formula:
        # Reclassify manual items that actually carry a formula.
        if item["kind"] == "manual":
            item["kind"] = "calculated"


def _walk_count(cat: GradeCategory) -> int:
    """Return the total number of form fetches required to enrich this tree."""
    n = 1  # the category itself
    for sub in cat["subcategories"]:
        n += _walk_count(sub)
    n += len(cat["items"])
    return n


def _enrich_tree(
        client: MoodleClientProtocol,
        course_id: CourseId,
        cat: GradeCategory,
        progress: ProgressCb | None,
        counter: list[int],
        total: int,
) -> None:
    _enrich_category(client, course_id, cat, progress, counter, total)
    for sub in cat["subcategories"]:
        _enrich_tree(client, course_id, sub, progress, counter, total)
    for item in cat["items"]:
        _enrich_item(client, course_id, item, progress, counter, total)


def _item_to_yaml(item: GradeItem) -> dict[str, Any]:
    out: dict[str, Any] = {
        "eid": item["eid"],
        "item_id": int(item["item_id"]),
        "name": item["name"],
        "kind": item["kind"],
        "grademax": _round(item.get("grademax")),
    }
    cmid = item.get("cmid")
    if cmid:
        out["cmid"] = int(cmid)
    idn = item.get("idnumber") or ""
    if idn:
        out["idnumber"] = idn
    if item.get("weight_override"):
        out["weight_override"] = True
        if item.get("weight") is not None:
            out["weight"] = _round(item["weight"])
    coef2 = item.get("aggregationcoef2")
    if coef2 is not None:
        out["aggregationcoef2"] = _round(coef2)
    if item.get("hidden"):
        out["hidden"] = True
    if item.get("locked"):
        out["locked"] = True
    # module_visible only meaningful for activity-backed items; default True so
    # the YAML stays tidy and round-trips for items we couldn't probe.
    if cmid and item.get("module_visible") is False:
        out["module_visible"] = False
    calc = item.get("calculation") or ""
    if calc:
        out["calculation"] = calc
    return out


def _category_to_yaml(cat: GradeCategory) -> dict[str, Any]:
    out: dict[str, Any] = {
        "eid": cat["eid"],
        "cat_id": int(cat["cat_id"]),
        "item_id": int(cat["item_id"]),
        "name": cat["name"],
        "aggregation": cat["aggregation"],
        "grademax": _round(cat.get("grademax")),
    }
    idn = cat.get("idnumber") or ""
    if idn:
        out["idnumber"] = idn
    if cat.get("droplow"):
        out["droplow"] = int(cat["droplow"])
    if cat.get("keephigh"):
        out["keephigh"] = int(cat["keephigh"])
    if not cat.get("aggregateonlygraded", True):
        out["aggregateonlygraded"] = False
    if cat.get("aggregateoutcomes"):
        out["aggregateoutcomes"] = True
    if cat.get("weight_override"):
        out["weight_override"] = True
        if cat.get("weight") is not None:
            out["weight"] = _round(cat["weight"])
    coef2 = cat.get("aggregationcoef2")
    if coef2 is not None:
        out["aggregationcoef2"] = _round(coef2)
    if cat.get("hidden"):
        out["hidden"] = True
    calc = cat.get("calculation") or ""
    if calc:
        out["calculation"] = calc

    children: list[dict[str, Any]] = []
    for sub in cat["subcategories"]:
        children.append({"category": _category_to_yaml(sub)})
    for item in cat["items"]:
        children.append({"item": _item_to_yaml(item)})
    if children:
        out["children"] = children
    return out


def pull(
        client: MoodleClientProtocol,
        course_id: CourseId,
        progress: ProgressCb | None = None,
) -> str:
    """Return a YAML string representing the current gradebook state."""
    tree: GradeTree = client.get_gradebook_tree(course_id)  # type: ignore[call-arg]
    total = _walk_count(tree["root"])
    counter = [0]
    _enrich_tree(client, course_id, tree["root"], progress, counter, total)
    _enrich_module_visibility(client, course_id, tree["root"])

    data: dict[str, Any] = {
        "course_id": int(course_id),
        "root": _category_to_yaml(tree["root"]),
    }
    yaml_text = yaml.safe_dump(
        data, sort_keys=False, allow_unicode=True, default_flow_style=False, width=120,
    )
    return _HEADER + yaml_text


def _enrich_module_visibility(
        client: MoodleClientProtocol,
        course_id: CourseId,
        root: GradeCategory,
) -> None:
    """Fill `module_visible` on activity-backed items using the course sections.

    One HTTP request fetches every section + module status, so this is cheap
    even on big courses — we don't add a request per item.
    """
    try:
        sections = client.get_course_sections(course_id)  # type: ignore[call-arg]
    except Exception:
        return
    visible_by_cmid: dict[int, bool] = {}
    for sec in sections:
        for m in sec.get("modules", []) or []:
            visible_by_cmid[int(m["cmid"])] = bool(m.get("visible", True))

    def _walk(cat: GradeCategory) -> None:
        for it in cat["items"]:
            cmid = it.get("cmid")
            if cmid and int(cmid) in visible_by_cmid:
                it["module_visible"] = visible_by_cmid[int(cmid)]
        for sub in cat["subcategories"]:
            _walk(sub)

    _walk(root)


# ---------------------------------------------------------------------------
# Pretty-printer for `gradebook show` — operates on the same enriched tree.
# ---------------------------------------------------------------------------

def render_tree(tree: GradeTree) -> str:
    """Return a human-readable indented summary of the gradebook tree.

    Used by `moodlectl gradebook show`. Does NOT fetch per-node forms — only
    information present on the live tree page is shown (no droplow/idnumber).
    """
    lines: list[str] = []

    def fmt_cat(cat: GradeCategory, depth: int) -> None:
        pad = "  " * depth
        weight = f" w={cat['weight']:g}" if cat.get("weight") else ""
        hidden = "  [hidden]" if cat.get("hidden") else ""
        lines.append(
            f"{pad}[{cat['eid']}] {cat['name']}  "
            f"(agg={cat['aggregation']}, max={cat.get('grademax', 0):g}{weight}){hidden}"
        )
        for sub in cat["subcategories"]:
            fmt_cat(sub, depth + 1)
        for it in cat["items"]:
            ipad = "  " * (depth + 1)
            kind = it.get("kind", "?")
            weight = f" w={it['weight']:g}" if it.get("weight") else ""
            cmid = f" cmid={it['cmid']}" if it.get("cmid") else ""
            hidden = "  [hidden]" if it.get("hidden") else ""
            lines.append(
                f"{ipad}- [{it['eid']}] {it['name']}  "
                f"({kind}, max={it.get('grademax', 0):g}{weight}{cmid}){hidden}"
            )

    fmt_cat(tree["root"], 0)
    return "\n".join(lines)


