def _collect_yaml_item_ids(node: dict[str, Any]) -> set[int]:
    """Walk a YAML root and return every referenced item_id (eid or item_id field)."""
    ids: set[int] = set()
    for child in node.get("children", []) or []:
        if "category" in child:
            ids |= _collect_yaml_item_ids(child["category"])
        elif "item" in child:
            it = child["item"]
            iid = it.get("item_id") or (int(it["eid"][2:]) if it.get("eid", "").startswith("ig") else None)
            if iid:
                ids.add(int(iid))
    return ids


def diff(
        client: MoodleClientProtocol,
        course_id: CourseId,
        yaml_text: str,
        *,
        live_tree: GradeTree | None = None,
) -> list[Change]:
    """Compare parsed YAML against the live gradebook; return ordered Change list.

    `live_tree` is accepted for tests / reuse; if omitted, pulled via the
    client (no per-form enrichment — only structural diffing of attributes
    available on the tree page plus calculations on category nodes).
    """
    parsed = yaml.safe_load(yaml_text)
    if not isinstance(parsed, dict) or "root" not in parsed:
        raise ValueError("YAML must have a top-level `root:` category node.")

    if live_tree is None:
        live_tree = client.get_gradebook_tree(course_id)  # type: ignore[call-arg]
        # Enrich with droplow/idnumber/calculation so the diff catches them
        total = _walk_count(live_tree["root"])
        counter = [0]
        _enrich_tree(client, course_id, live_tree["root"], None, counter, total)

    live_cats, live_items = _flatten_live(live_tree["root"])
    changes: list[Change] = []
    _walk_yaml(parsed["root"], int(live_tree["root"]["cat_id"]), live_cats, live_items, changes)

    # DELETE_ITEM: any live item not referenced in YAML AND with a cmid
    # (activity-backed → can be deleted via delete_module). Manual items
    # without a YAML match are skipped — Moodle doesn't expose web delete
    # for them and we'd just produce a useless Change.
    yaml_item_ids = _collect_yaml_item_ids(parsed["root"])
    for live_item in live_items.values():
        if int(live_item["item_id"]) in yaml_item_ids:
            continue
        cmid = live_item.get("cmid")
        if not cmid:
            # Manual item missing from YAML — refuse to emit a Change (would fail).
            continue
        changes.append(Change(
            kind=DELETE_ITEM,
            label=f"DELETE activity item {live_item['name']!r} ({live_item['eid']}, cmid={cmid})",
            target_eid=live_item["eid"],
            target_item_id=int(live_item["item_id"]),
            payload={"cmid": str(int(cmid))},
        ))

    return _order_changes(changes)


def _order_changes(changes: list[Change]) -> list[Change]:
    """Order changes so dependencies are satisfied at apply time.

    1. CREATE_CATEGORY (parent-before-child preserved by YAML walk order)
    2. CREATE_ITEM (manual items must exist before calculations reference them)
    3. UPDATE_CATEGORY
    4. UPDATE_ITEM
    5. SET_CALCULATION (last; idnumbers may have been just-set by UPDATE_ITEM)
    """
    order = {
        CREATE_CATEGORY: 0,
        CREATE_ITEM: 1,
        MOVE_ITEM: 2,            # before UPDATE/CALC so the item lives in its target category first
        UPDATE_CATEGORY: 3,
        UPDATE_ITEM: 4,
        SET_MODULE_VISIBLE: 5,   # after item updates (visibility lives on the module, not gradebook)
        SET_CALCULATION: 6,
        DELETE_ITEM: 7,          # last — removing items can break references; do after everything else
    }
    return sorted(changes, key=lambda c: order.get(c.kind, 99))


def push(
        client: MoodleClientProtocol,
        course_id: CourseId,
        changes: list[Change],
        *,
        progress: ProgressCb | None = None,
        continue_on_error: bool = False,
) -> list[tuple[Change, str]]:
    """Apply a list of Changes against Moodle. Returns [(change, error_msg), ...] for failures.

    Empty return list = all succeeded. With `continue_on_error=True`, push
    keeps going after a failure and reports everything at the end; otherwise
    the first failure raises.
    """
    failures: list[tuple[Change, str]] = []
    total = len(changes)
    # Maps used to resolve newly-created node ids inside this push session.
    created_cats_by_tag: dict[str, int] = {}    # own_tag → resolved cat_id
    created_cats: dict[str, int] = {}           # name → cat_id (legacy lookup)
    created_items: dict[str, int] = {}          # name → item_id

    # Find the course-total grade_item_id once — needed for the calc-form
    # idnumber trick on activity-backed items.
    course_total_item_id = _find_course_total_item_id(client, course_id)

    for i, ch in enumerate(changes, 1):
        if progress:
            progress(i, total, ch.label[:60])
        ch.course_total_item_id = course_total_item_id
        try:
            _apply_one(client, course_id, ch, created_cats, created_cats_by_tag, created_items)
        except Exception as exc:  # noqa: BLE001
            if continue_on_error:
                failures.append((ch, str(exc)))
                continue
            raise
    return failures


def _find_course_total_item_id(
        client: MoodleClientProtocol, course_id: CourseId,
) -> int:
    """Resolve the course-total grade_item id (the root category's item_id)."""
    tree = client.get_gradebook_tree(course_id)  # type: ignore[call-arg]
    return int(tree["root"]["item_id"])


def _resolve_parent_cat_id(
        ch: Change,
        created_cats_by_tag: dict[str, int],
) -> int:
    """Return ch.target_parent_cat_id or, if 0, resolve via pending_parent_tag."""
    if ch.target_parent_cat_id:
        return ch.target_parent_cat_id
    if ch.parent_cat_id:
        return ch.parent_cat_id
    if ch.pending_parent_tag and ch.pending_parent_tag in created_cats_by_tag:
        return created_cats_by_tag[ch.pending_parent_tag]
    return 0


def _apply_one(
        client: MoodleClientProtocol,
        course_id: CourseId,
        ch: Change,
        created_cats: dict[str, int],
        created_cats_by_tag: dict[str, int],
        created_items: dict[str, int],
) -> None:
    from moodlectl.types import GradeCategoryId as _Cid, GradeItemId as _Iid

    if ch.kind == CREATE_CATEGORY:
        name = ch.payload.get("fullname", "")
        # Resolve parent: it might be an existing cat (parent_cat_id) OR a
        # category being created earlier in this same push (pending_parent_tag).
        parent_cat = ch.parent_cat_id or created_cats_by_tag.get(ch.pending_parent_tag, 0)
        if not parent_cat:
            raise RuntimeError(
                f"CREATE_CATEGORY {name!r}: parent not resolved "
                f"(tag={ch.pending_parent_tag!r}). Create the parent first."
            )
        new_id = client.save_grade_category(
            course_id, _Cid(0), dict(ch.payload), parent_cat_id=_Cid(parent_cat),
        )
        created_cats[name] = int(new_id)
        if ch.own_tag:
            created_cats_by_tag[ch.own_tag] = int(new_id)
        # Moodle's create-category sometimes lands the new cat at root rather
        # than under the requested parent — if so, move it into place.
        try:
            tree = client.get_gradebook_tree(course_id)  # type: ignore[call-arg]
            def _find(cat):
                if cat["cat_id"] == int(new_id):
                    return cat
                for s in cat["subcategories"]:
                    r = _find(s)
                    if r:
                        return r
                return None
            placed = _find(tree["root"])
            if placed is not None and int(placed.get("parent_cat_id") or 0) != parent_cat:
                client.move_grade_item(  # type: ignore[call-arg]
                    course_id, item_eid=f"cg{int(new_id)}",
                    target_eid=f"cg{parent_cat}", first=True,
                )
        except Exception:
            pass
        return

    if ch.kind == UPDATE_CATEGORY:
        client.save_grade_category(course_id, _Cid(ch.target_cat_id), dict(ch.payload))
        return

    if ch.kind == CREATE_ITEM:
        if not ch.payload:
            # SKIP marker (activity-backed item that we can't create here).
            return
        name = ch.payload.get("itemname", "")
        parent_cat = ch.parent_cat_id or created_cats_by_tag.get(ch.pending_parent_tag, 0)
        if not parent_cat:
            raise RuntimeError(
                f"CREATE_ITEM {name!r}: parent not resolved "
                f"(tag={ch.pending_parent_tag!r})."
            )
        new_id = client.save_grade_item(
            course_id, _Iid(0), dict(ch.payload), parent_cat_id=_Cid(parent_cat),
        )
        created_items[name] = int(new_id)
        # If the YAML node has a calculation, push it now (we just got the id).
        yaml_calc = (ch.yaml_node.get("calculation") or "").strip()
        if yaml_calc:
            client.save_grade_calculation(course_id, new_id, yaml_calc)
        return

    if ch.kind == UPDATE_ITEM:
        if ch.via_calc_form:
            # idnumber update on activity-backed item — route through the
            # course-total calc form's idnumbers[] override.
            idnumber = ch.payload.get("idnumber", "")
            if ch.course_total_item_id == 0:
                raise RuntimeError("via_calc_form requires course_total_item_id to be set")
            current_formula, _ = client.get_grade_calculation(  # type: ignore[call-arg]
                course_id, _Iid(ch.course_total_item_id),
            )
            client.save_grade_calculation(
                course_id, _Iid(ch.course_total_item_id), current_formula,
                idnumber_overrides={_Iid(ch.target_item_id): idnumber},
            )
            return
        client.save_grade_item(course_id, _Iid(ch.target_item_id), dict(ch.payload))
        return

    if ch.kind == MOVE_ITEM:
        target_parent_cat = ch.target_parent_cat_id or created_cats_by_tag.get(ch.pending_parent_tag, 0)
        if not target_parent_cat:
            raise RuntimeError(
                f"MOVE_ITEM {ch.target_eid}: target parent not resolved "
                f"(tag={ch.pending_parent_tag!r})."
            )
        client.move_grade_item(
            course_id,
            item_eid=ch.target_eid,
            target_eid=f"cg{target_parent_cat}",
            first=True,
        )
        return

    if ch.kind == SET_MODULE_VISIBLE:
        cmid = int(ch.payload.get("cmid") or 0)
        if not cmid:
            raise RuntimeError(f"SET_MODULE_VISIBLE {ch.target_eid}: no cmid in payload")
        from moodlectl.types import Cmid as _Cmid
        client.set_module_visible(_Cmid(cmid), visible=(ch.payload.get("visible") == "1"))
        return

    if ch.kind == SET_CALCULATION:
        client.save_grade_calculation(
            course_id, _Iid(ch.target_item_id), ch.formula,
            idnumber_overrides=({_Iid(k): v for k, v in ch.idnumber_overrides.items()} if ch.idnumber_overrides else None),
        )
        return

    if ch.kind == DELETE_ITEM:
        # DELETE_ITEM handles activity-backed items only — calls delete_module
        # on the underlying cmid. Manual items can't be deleted via web (Moodle
        # JS-only modal); diff refuses to emit DELETE_ITEM for them.
        if ch.target_item_id == 0 or not ch.payload.get("cmid"):
            raise RuntimeError(
                f"DELETE_ITEM {ch.target_eid}: no cmid available — cannot delete "
                "(manual items must be deleted via the Moodle UI)."
            )
        from moodlectl.types import Cmid as _Cmid
        client.delete_module(_Cmid(int(ch.payload["cmid"])))  # type: ignore[arg-type]
        return

    raise RuntimeError(f"Unknown change kind: {ch.kind}")


def render_diff(changes: list[Change]) -> str:
    """Human-readable summary of a Change list (for --dry-run / push preview)."""
    if not changes:
        return "(no changes)"
    by_kind: dict[str, list[Change]] = {}
    for c in changes:
        by_kind.setdefault(c.kind, []).append(c)
    lines: list[str] = []
    for kind in [CREATE_CATEGORY, CREATE_ITEM, MOVE_ITEM, UPDATE_CATEGORY, UPDATE_ITEM,
                 SET_MODULE_VISIBLE, SET_CALCULATION, DELETE_ITEM]:
        items = by_kind.get(kind, [])
        if not items:
            continue
        lines.append(f"{kind} ({len(items)}):")
        for c in items:
            lines.append(f"  • {c.label}")
    return "\n".join(lines)
